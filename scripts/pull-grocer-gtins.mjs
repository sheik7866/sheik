#!/usr/bin/env node
/* Backfill GTINs from Grocer's public product catalogue.
 *
 * Foodstuffs' product-detail endpoint only exposes a barcode for some packs,
 * so scripts/pull-gtins.mjs leaves the rest blank. Grocer publishes a static
 * DuckDB file with a public product table (name, brand, size) and barcode
 * table, and this repository already reads it for Woolworths prices. Nothing
 * here touches woolworths.co.nz or any account-only endpoint.
 *
 * A code is only copied when a catalogue row and a Grocer product agree
 * exactly on brand, product name and pack size after normalisation, when that
 * match is unique, when the Grocer product has exactly one valid barcode, and
 * when the barcode passes its GTIN check digit. Ambiguous matches stay blank
 * rather than risk printing the wrong barcode.
 *
 *   node scripts/pull-grocer-gtins.mjs
 *   CACHE=/tmp/grocer node scripts/pull-grocer-gtins.mjs
 */

import fs from "node:fs";
import path from "node:path";
import vm from "node:vm";
import { DuckDBInstance } from "@duckdb/node-api";

const ROOT = path.resolve(import.meta.dirname, "..");
const BASE = "https://assets-prod.grocer.nz/public";
const OUT = process.env.OUT || path.join(ROOT, "data/gtins.js");
const CATALOGUE = process.env.CATALOGUE || path.join(ROOT, "data/catalogue.js");
const CACHE = process.env.CACHE || "/tmp/trolleybird-grocer-gtins";
const USER_AGENT = "TrolleybirdDemo/1.0 (price comparison demo; contact via GitHub)";

const sleep = (ms) => new Promise((resolve) => setTimeout(resolve, ms));

function readWindow(file, name) {
  const sandbox = { window: {} };
  vm.runInNewContext(fs.readFileSync(file, "utf8"), sandbox, { filename: file });
  const value = sandbox.window[name];
  if (!value) throw new Error(`No window.${name} in ${file}`);
  return value;
}

function sqlPath(file) {
  return `'${String(file).replace(/'/g, "''")}'`;
}

/* The CDN serves the DuckDB file itself, so the bytes are written as-is. */
async function download(url, file) {
  if (fs.existsSync(file) && fs.statSync(file).size > 0) return file;
  fs.mkdirSync(path.dirname(file), { recursive: true });
  for (let attempt = 0; attempt < 5; attempt += 1) {
    try {
      const res = await fetch(url, { headers: { "user-agent": USER_AGENT, referer: "https://grocer.nz/" } });
      if (res.status === 429 || res.status >= 500) {
        await sleep(2000 * (attempt + 1));
        continue;
      }
      if (!res.ok) throw new Error(`${res.status} ${res.statusText} for ${url}`);
      const bytes = Buffer.from(await res.arrayBuffer());
      if (!bytes.length) throw new Error(`empty response for ${url}`);
      fs.writeFileSync(`${file}.part`, bytes);
      fs.renameSync(`${file}.part`, file);
      return file;
    } catch (error) {
      if (attempt === 4) throw error;
      await sleep(1000 * (attempt + 1));
    }
  }
  throw new Error(`Gave up on ${url}`);
}

/* Mirrors the check in scripts/pull-gtins.mjs and app.js: a barcode is only
   stored when the demo can validate and render it. */
function checkDigit(base) {
  let sum = 0;
  let weight = 3;
  for (let index = base.length - 1; index >= 0; index -= 1) {
    sum += Number(base[index]) * weight;
    weight = 4 - weight;
  }
  return (10 - (sum % 10)) % 10;
}

function cleanGtin(raw) {
  let digits = String(raw || "").replace(/\D/g, "");
  if (!digits) return "";
  if (digits.length === 14) digits = digits.replace(/^0+/, "");
  // A UPC-A filed without its leading zero (050000426942 -> 50000426942).
  if (digits.length === 11) digits = `0${digits}`;
  if (digits.length === 12) digits = `0${digits}`;
  if (digits.length !== 8 && digits.length !== 13) return "";
  if (Number(digits.at(-1)) !== checkDigit(digits.slice(0, -1))) return "";
  return digits;
}

const normalizeText = (value) =>
  String(value || "")
    .toLowerCase()
    .normalize("NFKD")
    .replace(/[^a-z0-9]+/g, " ")
    .trim()
    .replace(/\s+/g, " ");

const normalizeSize = (value) => String(value || "").toLowerCase().replace(/\s+/g, "");

function writeOutput(gtins) {
  const sorted = Object.fromEntries(
    Object.entries(gtins).sort(([left], [right]) => left.localeCompare(right))
  );
  const count = Object.keys(sorted).length;
  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  fs.writeFileSync(
    OUT,
    `/* Generated by scripts/pull-gtins.mjs (store product records) and
   scripts/pull-grocer-gtins.mjs (Grocer's public barcode table) on ${new Date()
     .toISOString()
     .slice(0, 10)}.
   ${count.toLocaleString("en-NZ")} real GTINs keyed by Foodstuffs product id. Only codes with a
   valid check digit are included; produce PLUs and other internal codes are not barcodes.
   Re-run the scripts to add new products; do not edit by hand. */
window.GROCER_GTINS = ${JSON.stringify(sorted)};\n`
  );
  console.log(`Wrote ${count} GTINs to ${OUT}`);
}

async function main() {
  const existing = readWindow(OUT, "GROCER_GTINS");
  const catalogue = readWindow(CATALOGUE, "GROCER_CATALOGUE");
  const rows = Array.isArray(catalogue?.items) ? catalogue.items : [];
  if (!rows.length) throw new Error(`No catalogue items in ${CATALOGUE}`);

  const database = await download(`${BASE}/base_v3.duckdb.br`, path.join(CACHE, "base_v3.duckdb"));
  const instance = await DuckDBInstance.create(":memory:");
  const connection = await instance.connect();
  await connection.run(`attach ${sqlPath(database)} as base (READ_ONLY)`);
  const result = await connection.runAndReadAll(`
    select p.id, p.name, p.brand, p.size, b.barcode
    from base.public_products p
    join base.public_barcodes b on b.product_id = p.id
    where p.redirected_to is null
  `);

  const products = new Map();
  for (const row of result.getRowObjects()) {
    const code = cleanGtin(row.barcode);
    if (!code) continue;
    const key = String(row.id);
    if (!products.has(key)) {
      products.set(key, {
        name: row.name,
        brand: row.brand,
        size: row.size,
        codes: new Set(),
      });
    }
    products.get(key).codes.add(code);
  }

  const byKey = new Map();
  for (const product of products.values()) {
    if (product.codes.size !== 1) continue;
    const key = `${normalizeText(product.brand)}|${normalizeText(product.name)}|${normalizeSize(
      product.size
    )}`;
    if (!byKey.has(key)) byKey.set(key, []);
    byKey.get(key).push([...product.codes][0]);
  }

  const gtins = { ...existing };
  let matched = 0;
  let ambiguous = 0;
  for (const row of rows) {
    const id = String(row[0] || "");
    if (!id || gtins[id]) continue;
    const key = `${normalizeText(row[2])}|${normalizeText(row[1])}|${normalizeSize(row[3])}`;
    const codes = byKey.get(key);
    if (!codes) continue;
    if (codes.length !== 1) {
      ambiguous += 1;
      continue;
    }
    gtins[id] = codes[0];
    matched += 1;
  }

  writeOutput(gtins);
  console.log(
    `${matched.toLocaleString("en-NZ")} products matched by brand, name and size; ` +
      `${ambiguous.toLocaleString("en-NZ")} ambiguous matches left blank; ` +
      `${Object.keys(gtins).length.toLocaleString("en-NZ")} total mapped`
  );
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
