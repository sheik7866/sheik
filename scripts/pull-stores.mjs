#!/usr/bin/env node
/* Pull every PAK'nSAVE and New World branch from the stores' public locator.
 *
 *   node scripts/pull-stores.mjs
 *   OUT=/tmp/stores.js node scripts/pull-stores.mjs
 *
 * Both banners expose their branch list from the same anonymous edge API the
 * sites use. The demo needs the branch name, island and address so the store
 * picker can offer every real branch, and so each branch can be priced from
 * its banner's North or South Island price list.
 */

import fs from "node:fs";
import path from "node:path";

const ROOT = path.resolve(import.meta.dirname, "..");
const OUT = process.env.OUT || path.join(ROOT, "data/stores.js");
const TODAY = new Intl.DateTimeFormat("en-CA", {
  timeZone: "Pacific/Auckland",
}).format(new Date());

const BRANDS = {
  pns: {
    name: "PAK'nSAVE",
    api: "https://api-prod.paknsave.co.nz/v1/edge",
    site: "https://www.paknsave.co.nz",
  },
  nw: {
    name: "New World",
    api: "https://api-prod.newworld.co.nz/v1/edge",
    site: "https://www.newworld.co.nz",
  },
};

const USER_AGENT =
  "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/139.0.0.0 Safari/537.36";

async function guestToken(brand) {
  const res = await fetch(`${brand.site}/api/user/get-current-user`, {
    method: "POST",
    headers: {
      "Content-Type": "application/json",
      Origin: brand.site,
      Referer: `${brand.site}/`,
      "User-Agent": USER_AGENT,
    },
    body: JSON.stringify({ fingerprintUser: "grocer-demo-price-check" }),
  });
  if (!res.ok) throw new Error(`${brand.name} guest token ${res.status}`);
  const json = await res.json();
  if (!json.access_token) throw new Error(`${brand.name} guest token had no access_token`);
  return json.access_token;
}

async function fetchStores(brand, token) {
  const res = await fetch(`${brand.api}/store`, {
    headers: { Authorization: `Bearer ${token}`, "User-Agent": USER_AGENT },
  });
  if (!res.ok) throw new Error(`${brand.name} store list ${res.status}`);
  const json = await res.json();
  return Array.isArray(json) ? json : json.stores || [];
}

function branchOf(name, brandName) {
  const full = String(name || "").trim();
  // One PAK'nSAVE branch is listed as "PAKnSAVE Wairau Road", so accept the
  // apostrophe-less spelling too.
  const escaped = brandName.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
  const prefix = new RegExp(`^(?:${escaped}|${escaped.replace(/'/g, "'?")})\\s+`, "i");
  return full.replace(prefix, "").trim() || full;
}

async function main() {
  const stores = [];
  for (const [key, brand] of Object.entries(BRANDS)) {
    const token = await guestToken(brand);
    const list = await fetchStores(brand, token);
    for (const store of list) {
      if (!store?.id || !store.name) continue;
      const region = store.region === "SI" ? "SI" : "NI";
      stores.push({
        id: String(store.id),
        brand: key,
        name: brand.name,
        branch: branchOf(store.name, brand.name),
        region,
        address: String(store.address || "").trim(),
        latitude: Number.isFinite(store.latitude) ? Number(store.latitude.toFixed(5)) : null,
        longitude: Number.isFinite(store.longitude) ? Number(store.longitude.toFixed(5)) : null,
      });
    }
    console.log(`${brand.name}: ${list.length} branches`);
  }

  stores.sort(
    (a, b) =>
      a.brand.localeCompare(b.brand) ||
      a.branch.localeCompare(b.branch, "en-NZ") ||
      a.address.localeCompare(b.address, "en-NZ")
  );

  const payload = {
    fetchedAt: TODAY,
    source: "PAK'nSAVE and New World public store locators",
    stores,
  };

  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  fs.writeFileSync(
    OUT,
    `/* Generated by scripts/pull-stores.mjs from the public store locators on ${TODAY}.
   ${stores.length.toLocaleString("en-NZ")} branches: every PAK'nSAVE and New World
   in New Zealand, with the island whose price list each branch uses.
   Do not edit by hand — re-run the script instead. */
window.GROCER_STORES = ${JSON.stringify(payload, null, 2)};
`
  );
  console.log(
    `Wrote ${stores.length} branches to ${OUT} ` +
      `(PAK'nSAVE ${stores.filter((s) => s.brand === "pns").length}, ` +
      `New World ${stores.filter((s) => s.brand === "nw").length})`
  );
}

main().catch((error) => {
  console.error(`[stores] FAILED ${error.message}`);
  process.exitCode = 1;
});
